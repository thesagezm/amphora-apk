#!/usr/bin/env python3
"""Generate Android launcher assets from Amphora's 1024x1024 iOS icon.

The iOS icon (Tools/appicon-source.png, generated by the iOS repo's
Tools/gen_appicon.py) is used as the adaptive-icon *background* layer:
Android's mask crops the corners, exactly like iOS applies its squircle
mask, so the icon reads identically. The foreground layer is transparent.

minSdk is 26 (Android 8.0), which is where adaptive icons began — no
legacy density PNGs are needed.

    python3 Tools/gen_android_icons.py
"""

from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SRC = HERE / "appicon-source.png"
RES = HERE.parent / "app" / "src" / "main" / "res"

# The adaptive-icon layer is 108dp; these are its pixel sizes per density.
LAYERS = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}

src = Image.open(SRC).convert("RGB")
for density, size in LAYERS.items():
    out = RES / f"drawable-{density}"
    out.mkdir(parents=True, exist_ok=True)
    src.resize((size, size), Image.LANCZOS).save(out / "ic_launcher_bg.png")
    print(f"d drawable-{density}/ic_launcher_bg.png {size}x{size}")
